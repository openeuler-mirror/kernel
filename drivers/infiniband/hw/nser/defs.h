#define NSER_RING_MOVE_HEAD(_ring, _retcode) \
	{ \
		u32 size; \
		size = NSER_RING_SIZE(_ring);  \
		if (!NSER_RING_FULL_ERR(_ring)) { \
			NSER_RING_CURRENT_HEAD(_ring) = \
					(NSER_RING_CURRENT_HEAD(_ring) + 1) % size; \
			(_retcode) = 0; \
		} else { \
			(_retcode) = -ENOMEM; \
		} \
	}

#define NSER_RING_NEXT_HEAD(_ring, index) \
	{ \
		register u32 size; \
		size = (_ring).size;  \
		if (!NSER_RING_FULL_ERR(_ring)) { \
			index = ((_ring).head + 1) % size; \
		} else { \
			index = -1;\
		} \
	}

#define NSER_RING_MOVE_HEAD_BY_COUNT(_ring, _count, _retcode) \
	{ \
		register u32 size; \
		size = (_ring).size; \
		if ((NSER_RING_USED_QUANTA(_ring) + (_count)) < size) { \
			(_ring).head = ((_ring).head + (_count)) % size; \
			(_retcode) = 0; \
		} else { \
			(_retcode) = -ENOSPC; \
		} \
	}
#define NSER_SQ_RING_MOVE_HEAD(_ring, _retcode) \
