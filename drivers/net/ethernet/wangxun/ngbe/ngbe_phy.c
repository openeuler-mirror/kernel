static void ngbe_phy_setup_jl3113_init(struct ngbe_hw *hw,
				       const struct ngbe_phy_jl31xx_init_reg_map *tbl, size_t size)
{
	u16 revision = 0;
	u16 reg_data = 0;
	u16 retries = 10;
	u16 value = 0;
	u16 i = 0;

	ngbe_phy_read_reg_mmd_baset1(hw, 0x114, 0x1F, &revision);
	if ((revision & 0xf000) == BIT(14)) {
		for (i = 0; i < size; i++) {
			ngbe_phy_read_reg_mmd_baset1(hw, tbl[i].regaddr, tbl[i].devaddr, &reg_data);
			reg_data &= ~tbl[i].clear_bits;
			reg_data |= tbl[i].set_bits;
			ngbe_phy_write_reg_mmd_baset1(hw, tbl[i].regaddr, tbl[i].devaddr, reg_data);
		}
		usleep_range(5000, 10000);
	}

	/* config master-slave mode */
	ngbe_phy_read_reg_mmd_baset1(hw, 0x834, 0x1, &value);
	if (hw->phy.baset1_mode == 0)
		value |= BIT(14);
	else
		value &= ~BIT(14);
	ngbe_phy_write_reg_mmd_baset1(hw, 0x834, 0x1, value);

	ngbe_phy_read_reg_mmd_baset1(hw, 0x0, 0x1, &value);
	value |= BIT(6) | BIT(11);
	ngbe_phy_write_reg_mmd_baset1(hw, 0x0, 0x1, value);

	/* config phy mode */
	ngbe_phy_read_reg_mmd_baset1(hw, 0x8000, 0x3, &value);
	value &= ~0xf;
	ngbe_phy_write_reg_mmd_baset1(hw, 0x8000, 0x3, value);

	/* config tx/rx delay */
	ngbe_phy_read_reg_mmd_baset1(hw, 0x8800, 0x3, &value);

	/* enable rx_delay, disable tx_delay */
	value &= ~BIT(15);
	value |= BIT(14);

	ngbe_phy_write_reg_mmd_baset1(hw, 0x8800, 0x3, value);

	/* soft reset phy */
	ngbe_phy_read_reg_mmd_baset1(hw, 0x0, 0x1, &value);
	value |= BIT(15);
	if ((revision & 0xf000) == BIT(14))
		usleep_range(2000, 4000);
	ngbe_phy_write_reg_mmd_baset1(hw, 0x0, 0x1, value);

	do {
		usleep_range(10000, 20000);
		ngbe_phy_read_reg_mmd_baset1(hw, 0x0, 0x1, &value);
	} while (value & BIT(15) && --retries);
}

