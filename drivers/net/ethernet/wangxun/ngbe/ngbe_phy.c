static u32 ngbe_load_cfg_ly1211s(struct ngbe_hw *hw)
{
	struct ngbe_adapter *adapter = hw->back;
	u16 cfg_enable_ack = 0x0;
	u16 cfg_enable = 0x0;
	u16 value = 0x0;
	u32 i;

	// get phy chip version
	ngbe_phy_read_reg_ext_ly1211s(hw, 0xC419,
				      NGBE_LY1211S_PAGE_SELECT_UTP, &value);

	ngbe_phy_write_reg_ext_ly1211s(hw, 0xC460,
				       NGBE_LY1211S_PAGE_SELECT_UTP, 0x85);

	ngbe_phy_write_reg_ext_ly1211s(hw, 0xC45C,
				       NGBE_LY1211S_PAGE_SELECT_UTP, 0x1);

	ngbe_phy_write_reg_ext_ly1211s(hw, 0xC413,
				       NGBE_LY1211S_PAGE_SELECT_UTP, 0x85);

	ngbe_phy_write_reg_ly1211s(hw, 0x16, 0, 0x1);
	ngbe_phy_write_reg_ly1211s(hw, 0xe, 0, 0xC800);

	if (value == 0x03)
		for (i = 0; i < ARRAY_SIZE(LINKYUM_LY1211V3_CFG); i++)
			ngbe_phy_write_reg_ly1211s(hw, 0xd, 0, LINKYUM_LY1211V3_CFG[i]);
	else if (value == 0x2)
		for (i = 0; i < ARRAY_SIZE(LINKYUM_LY1211V2_CFG); i++)
			ngbe_phy_write_reg_ly1211s(hw, 0xd, 0, LINKYUM_LY1211V2_CFG[i]);

	ngbe_phy_write_reg_ly1211s(hw, 0x16, 0, 0x0);
	ngbe_phy_write_reg_ext_ly1211s(hw, 0xC45C,
				       NGBE_LY1211S_PAGE_SELECT_UTP, 0x0);

	for (i = 0; i < 5; i++) {
		ngbe_phy_read_reg_ext_ly1211s(hw, 0xC45D,
					      NGBE_LY1211S_PAGE_SELECT_UTP, &cfg_enable);
		ngbe_phy_read_reg_ext_ly1211s(hw, 0xC45E,
					      NGBE_LY1211S_PAGE_SELECT_UTP, &cfg_enable_ack);

		if (cfg_enable == 0x85 && cfg_enable_ack == 0x85)
			break;
		msleep(20);
	}

	if (i == 5)
		e_info(hw, "Phy LY1211S Config Load Time Out\n");

	/* wait for reset done*/
	msleep(20);

	return 0;
}

